// A. Register User (Returns only confirmation & username, NO keys/tokens!)
app.post("/register", (req, res) => {
  const { username, password } = req.body;

  if (!username || !password) {
    return res.status(400).json({ error: "Username and password are required" });
  }

  if (USERS_DB[username]) {
    return res.status(409).json({ error: "User already exists. Choose another username." });
  }

  // Save the user with no API key initially
  USERS_DB[username] = {
    password,
    apiKey: null,
    bearerToken: `bearer-token-${Math.random().toString(36).substring(2, 12)}`,
  };

  res.status(201).json({
    message: "User registered successfully! You can now generate an API key at GET /generate-api-key",
    username,
  });
});

// B. Dedicated Route to Generate an API Key (Protected by Basic Auth)
// Requires username & password via Basic Auth or Body to verify ownership!
app.get("/generate-api-key", (req, res) => {
  // Check Basic Auth to know which registered user is requesting the key
  const authHeader = req.headers["authorization"];
  let username, password;

  if (authHeader && authHeader.startsWith("Basic ")) {
    const base64Credentials = authHeader.split(" ")[1];
    const decoded = Buffer.from(base64Credentials, "base64").toString("utf-8");
    [username, password] = decoded.split(":");
  } else if (req.query.username && req.query.password) {
    // Alternatively allows passing ?username=...&password=... in query for convenience
    username = req.query.username;
    password = req.query.password;
  }

  if (!username || !password) {
    return res.status(401).json({
      error: "Unauthorized: Please provide your registered credentials via Basic Auth (or ?username=...&password=...)",
    });
  }

  const user = USERS_DB[username];
  if (!user || user.password !== password) {
    return res.status(401).json({ error: "Unauthorized: Invalid username or password" });
  }

  // Generate a new unique API Key for this user and store it in their account
  const newApiKey = `api-key-${Math.random().toString(36).substring(2, 10)}`;
  user.apiKey = newApiKey;

  console.log(`🔑 Generated API key for ${username}: ${newApiKey}`);

  res.json({
    message: "API key generated successfully!",
    username,
    apiKey: newApiKey,
  });
});

